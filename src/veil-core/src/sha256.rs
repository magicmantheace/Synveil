//! SHA-256 (FIPS 180-4), implemented in-tree.
//!
//! The offline dependency registry pinned for this workspace carries
//! no SHA-2 crate, and the A/B updater needs SHA-256 for release
//! payload digests (docs/AB_UPDATER.md). This is a small, auditable,
//! one-shot/streaming implementation used only for hashing data the
//! caller already holds; it is validated against published vectors
//! in this module's tests.

